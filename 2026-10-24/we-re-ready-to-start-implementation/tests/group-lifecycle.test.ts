import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('new groups are empty; leaving revokes only your access and preserves history', async () => {
 const db = new PGlite();
 const owner = '11111111-1111-4111-8111-111111111111';
 const other = '22222222-2222-4222-8222-222222222222';
 try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
   create schema auth; create table auth.users(id uuid primary key);
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   grant usage on schema auth,public to authenticated,anon,service_role;
   grant execute on function auth.uid() to authenticated,anon,service_role;
   create publication supabase_realtime; insert into auth.users values('${owner}'),('${other}');`);
  const asUser = async (id: string) => db.exec(`reset role;set role authenticated;select set_config('request.jwt.claim.sub','${id}',false);`);
  for (const file of ['001_phase1.sql','002_conversational_routing.sql','003_agent_studio.sql','004_friend_library.sql']) await db.exec(await readFile('supabase/migrations/'+file,'utf8'));
  await asUser(owner);
  const old = (await db.query<{id:string}>("select public.create_room('Existing','Alex') id")).rows[0].id;
  await db.exec('reset role');
  await db.exec(await readFile('supabase/migrations/006_group_lifecycle.sql','utf8'));
  await db.exec(await readFile('supabase/migrations/007_companion_notices.sql','utf8'));
  await db.exec(await readFile('supabase/migrations/008_zorad.sql','utf8'));
  await db.exec(await readFile('supabase/migrations/009_private_chat_names.sql','utf8'));
  await asUser(owner);
  assert.equal((await db.query('select * from public.room_friends($1)',[old])).rows.length,4);
  const room = (await db.query<{id:string}>("select public.create_room('Fresh','Alex') id")).rows[0].id;
  assert.equal((await db.query('select * from public.room_friends($1)',[room])).rows.length,1);
  await assert.rejects(db.query('select public.remove_friend($1,$2)',[room,'zorad']), /Only the creator/);
  const config = JSON.stringify({name:'Nova', personality:'Friendly',specialty:'Ideas',avatar:'N',skills:[]});
  const original = (await db.query<{id:string}>('select public.save_studio_friend(null,null,$1::jsonb) id',[config])).rows[0].id;
  const fork = (await db.query<{id:string}>('select public.save_studio_friend(null,$1,$2::jsonb) id',['zorad',config])).rows[0].id;
  assert.ok(fork.startsWith('custom-'));
  const solo = (await db.query<{id:string}>('select public.start_friend_chat($1,$2) id',[[fork],'Alex'])).rows[0].id;
  assert.equal((await db.query<{name:string}>('select name from public.rooms where id=$1',[solo])).rows[0].name,'Nova');
  assert.ok((await db.query<{id:string}>('select id from public.room_friends($1)',[solo])).rows.some(a=>a.id==='zorad'));
  const added = (await db.query<{id:string}>('select public.add_friend_to_room($1,$2) id',[original,room])).rows[0].id;
  await db.query('select public.add_friend_to_room($1,$2)',[original,room]);
  await asUser(other);
  await assert.rejects(db.query('select public.remove_friend($1,$2)',[room,added]), /Room not found/);
  assert.equal((await db.query('select * from public.messages where room_id=$1',[room])).rows.length,0);
  await asUser(owner);
  await db.query('select public.remove_friend($1,$2)',[room,added]);
  const notices = (await db.query<{content:string;event_type:string}>('select content,event_type from public.messages where room_id=$1 order by created_at',[room])).rows;
  assert.deepEqual(notices.map(row=>row.content), ['Alex added Nova.', 'Alex removed Nova.']);
  assert.deepEqual(notices.map(row=>row.event_type), ['companion_added', 'companion_removed']);
  await db.exec(`reset role; insert into public.members values('${room}','${other}','Jo');set role service_role;`);
  await assert.rejects(db.query("select public.submit_routed_message(gen_random_uuid(),$1,$2,'Hi',$3)",[room,owner,JSON.stringify({agentId:'ravi',complexity:'LOW'})]),/not available/);
  await db.query("select public.submit_routed_message(gen_random_uuid(),$1,$2,'Hello people',$3)",[room,owner,JSON.stringify({agentId:null,complexity:'LOW'})]);
  await asUser(owner);
  await db.query('select public.leave_room($1)',[room]);
  assert.equal((await db.query('select id from public.rooms where id=$1',[room])).rows.length,0);
  assert.equal((await db.query('select * from public.messages where room_id=$1',[room])).rows.length,0);
  await asUser(other);
  assert.equal((await db.query('select id from public.rooms where id=$1',[room])).rows.length,1);
  assert.equal((await db.query('select * from public.messages where room_id=$1',[room])).rows.length,3);
  await db.exec('reset role;set role service_role;');
  await assert.rejects(db.query("select public.submit_routed_message(gen_random_uuid(),$1,$2,'No access',$3)",[room,owner,JSON.stringify({agentId:null,complexity:'LOW'})]),/Room not found/);
  await db.exec('reset role;set role anon;');
  await assert.rejects(db.query('select public.leave_room($1)',[room]),/permission denied/);
 } finally { await db.close(); }
});
